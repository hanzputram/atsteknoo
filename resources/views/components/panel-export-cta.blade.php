{{-- Client script for smooth scrolling & copy-to-clipboard feedback --}}
<script>
(function() {
    const copyBtn = document.getElementById('btn-copy-email');
    if (copyBtn) {
        copyBtn.addEventListener('click', function() {
            const email = this.getAttribute('data-email') || 'export@atstekno.com';
            const iconCopy = this.querySelector('.icon-copy');
            const iconCheck = this.querySelector('.icon-check');
            const copyText = this.querySelector('.copy-text');

            navigator.clipboard.writeText(email).then(() => {
                if (iconCopy) iconCopy.style.display = 'none';
                if (iconCheck) iconCheck.style.display = 'inline-block';
                const currentLang = document.documentElement.getAttribute('lang') || 'en';
                copyText.textContent = (currentLang === 'fr') ? 'Copié !' : 'Copied!';
                
                setTimeout(() => {
                    if (iconCopy) iconCopy.style.display = 'inline-block';
                    if (iconCheck) iconCheck.style.display = 'none';
                    copyText.textContent = (currentLang === 'fr') ? "Copier l'Email" : 'Copy Email';
                }, 2500);
            }).catch(err => {
                console.warn('Clipboard write failed:', err);
            });
        });
    }

    // Auto-smooth scroll if hash matches #export, #export-inquiry, #inquiry, or #contact-export
    function checkHashScroll() {
        const h = window.location.hash.toLowerCase();
        if (['#export', '#export-inquiry', '#inquiry', '#contact-export'].includes(h)) {
            const target = document.getElementById('export-inquiry');
            if (target) {
                setTimeout(() => {
                    target.scrollIntoView({ behavior: 'smooth', block: 'start' });
                }, 200);
            }
        }
    }
    window.addEventListener('DOMContentLoaded', checkHashScroll);
    window.addEventListener('hashchange', checkHashScroll);
})();
</script>
